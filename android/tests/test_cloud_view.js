const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const html=fs.readFileSync('android/app/src/main/assets/local/index.html','utf8');
const source=html.slice(html.indexOf('const decimal1='),html.indexOf('function renderHomeThresholds'));
const nodes={};
const get=id=>nodes[id]||(nodes[id]={textContent:'',after(){},classList:{values:new Set(),toggle(key,on){if(on)this.values.add(key);else this.values.delete(key);}}});
const box={get,Intl,message(){},networkLeds(){},document:{querySelector(){return null;},createElement(){return {};}}};
box.window=box;vm.createContext(box);vm.runInContext(source,box);
vm.runInContext(fs.readFileSync('android/app/src/main/assets/cloud.js','utf8'),box);
const sample=(at,total)=>({uptime_ms:at,water:{seen_pulses:true,total_l_estimate:total,calibrated:true}});
box.updateLiquidPanels(sample(10000,10));box.updateLiquidPanels(sample(40000,11));
assert.equal(get('homeCoolingRate').textContent,'120,0 л/ч');
for(let i=0;i<10;i++)box.updateLiquidPanels(sample(40000,11));
assert.equal(get('homeCoolingRate').textContent,'120,0 л/ч','Repeated fresh cache must retain measured rate');
assert(get('rigArtStage').classList.values.has('hasCooling'));
box.updateLiquidPanels(sample(70000,11.5));assert.equal(get('homeCoolingRate').textContent,'60,0 л/ч');
box.updateLiquidPanels(sample(1000,0));assert.equal(get('homeCoolingRate').textContent,'— л/ч','Counter restart must clear old measurement');
box.updateLiquidPanels(sample(31000,1));assert.equal(get('homeCoolingRate').textContent,'120,0 л/ч');
box.updateLiquidPanels(null);assert.equal(get('homeCoolingRate').textContent,'— л/ч','Lost/stale connection must clear measurement');
assert(!get('rigArtStage').classList.values.has('hasCooling'));
console.log('PASS cloud adapter retains measured cooling across cached samples, updates on new samples, clears on reset/disconnect');
