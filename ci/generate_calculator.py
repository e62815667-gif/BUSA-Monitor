"""Generate shared coefficient tables and embed offline browser assets; --check never writes."""
from pathlib import Path
import json,sys
root=Path(__file__).resolve().parents[1];sketch=root/'firmware/BUSA_1M_WIFI_3v_GOOGLE'
co=json.loads((root/'calculator/oiml-coefficients.json').read_text())
license=(root/'third_party/alcoholometry-core/LICENSE').read_text()
notice='/* Coefficients adapted from alcoholometry-core (MIT), David Platt.\n'+license+'*/\n'
outputs={}
outputs[sketch/'BUSA_CalcCoefficients.h']=notice+'#pragma once\nstatic const double BUSA_CALC_COEFFICIENTS[12][7]={\n'+',\n'.join('{'+','.join(str(x) for x in ([0]*(7-len(r))+r))+'}' for r in co)+'\n};\n'
js=notice+'const BUSA_CALC_COEFFICIENTS='+json.dumps(co,separators=(',',':'))+';\n'+(root/'calculator/core.js').read_text()+'\n'+(root/'calculator/ui.js').read_text()
outputs[root/'calculator.js']=js
css=(root/'calculator.css').read_text()
outputs[sketch/'BUSA_CalculatorWeb.h']='#pragma once\n// Generated by ci/generate_calculator.py; offline assets, no controller writes.\nstatic const char BUSA_CALCULATOR_JS[] PROGMEM=R"BUSACALC('+js+')BUSACALC";\nstatic const char BUSA_CALCULATOR_CSS[] PROGMEM=R"BUSACALC('+css+')BUSACALC";\n'
for path,content in outputs.items():
 if '--check' in sys.argv:assert path.read_text()==content,str(path)
 else:path.write_text(content)
print('PASS calculator coefficient/assets generation'+(' (read-only)' if '--check' in sys.argv else ''))
